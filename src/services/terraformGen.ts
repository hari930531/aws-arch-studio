export interface TfNodeInput {
  id: string;
  service: string;
  label: string;
  config?: {
    instanceType?: string;
    storageGb?: number;
    volumeType?: string;
    platform?: string;
    billingOption?: string;
    instanceCount?: number;
    lcus?: number;
    vpcName?: string;
  };
}

export interface TfEdgeInput {
  id: string;
  source: string;
  target: string;
  linkType?: string;
  label?: string;
}

export interface TerraformBundle {
  'provider.tf': string;
  'variables.tf': string;
  'main.tf': string;
  'outputs.tf': string;
}

function sanitizeTfName(raw: string, fallback: string): string {
  const cleaned = raw
    .toLowerCase()
    .replace(/[^a-z0-9_]+/g, '_')
    .replace(/^_+|_+$/g, '');
  if (!cleaned) return fallback;
  return /^[0-9]/.test(cleaned) ? `res_${cleaned}` : cleaned;
}

export function generateTerraformBundle(
  region: string,
  nodes: TfNodeInput[],
  edges: TfEdgeInput[]
): TerraformBundle {
  const safeRegion = region || 'ap-south-1';

  const providerTf = `terraform {
  required_version = ">= 1.5.0"

  required_providers {
    aws = {
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }
  }
}

provider "aws" {
  region = var.aws_region

  default_tags {
    tags = {
      ManagedBy   = "AWS-Arch-Studio"
      Environment = var.environment
    }
  }
}
`;

  const variablesTf = `variable "aws_region" {
  description = "AWS Region selected in AWS Arch Studio"
  type        = string
  default     = "${safeRegion}"
}

variable "environment" {
  description = "Deployment environment name"
  type        = string
  default     = "production"
}

variable "vpc_cidr" {
  description = "Default CIDR block for VPC"
  type        = string
  default     = "10.0.0.0/16"
}
`;

  const mainBlocks: string[] = [
    `# Generated by AWS Arch Studio (VS Code Extension)`,
    `# Total Components: ${nodes.length} | Connections: ${edges.length}\n`,
    `data "aws_availability_zones" "available" {
  state = "available"
}\n`
  ];

  const outputBlocks: string[] = [
    `# Architecture Outputs\n`
  ];

  // Track primary VPC / Subnet / SG names if created so child resources can reference them cleanly
  let primaryVpcRef = 'aws_vpc.main_vpc.id';
  let primarySubnetRef = 'aws_subnet.main_subnet.id';
  let primarySgRef = 'aws_security_group.main_sg.id';

  const hasVpc = nodes.some((n) => n.service === 'VPC');
  const hasSubnet = nodes.some((n) => n.service === 'Subnet');
  const hasSg = nodes.some((n) => n.service === 'SecurityGroup');

  if (!hasVpc) {
    mainBlocks.push(`resource "aws_vpc" "main_vpc" {
  cidr_block           = var.vpc_cidr
  enable_dns_hostnames = true
  enable_dns_support   = true

  tags = {
    Name = "arch-studio-vpc"
  }
}\n`);
  }

  if (!hasSubnet) {
    mainBlocks.push(`resource "aws_subnet" "main_subnet" {
  vpc_id                  = ${primaryVpcRef}
  cidr_block              = "10.0.1.0/24"
  availability_zone       = data.aws_availability_zones.available.names[0]
  map_public_ip_on_launch = true

  tags = {
    Name = "arch-studio-subnet-1"
  }
}\n`);
  }

  if (!hasSg) {
    mainBlocks.push(`resource "aws_security_group" "main_sg" {
  name        = "arch-studio-sg"
  description = "Managed by AWS Arch Studio"
  vpc_id      = ${primaryVpcRef}

  ingress {
    from_port   = 443
    to_port     = 443
    protocol    = "tcp"
    cidr_blocks = ["0.0.0.0/0"]
  }

  egress {
    from_port   = 0
    to_port     = 0
    protocol    = "-1"
    cidr_blocks = ["0.0.0.0/0"]
  }
}\n`);
  }

  const usedNames = new Set<string>();
  const uniqueName = (base: string) => {
    let candidate = base;
    let i = 2;
    while (usedNames.has(candidate)) {
      candidate = `${base}_${i++}`;
    }
    usedNames.add(candidate);
    return candidate;
  };

  let subnetIdx = 0;

  for (const node of nodes) {
    if (node.service === 'Region' || node.service === 'AZ' || node.service === 'TextNote') {
      continue;
    }

    const resName = uniqueName(sanitizeTfName(node.label, node.service.toLowerCase()));
    const cfg = node.config || {};

    switch (node.service) {
      case 'VPC': {
        if (!hasVpc || primaryVpcRef === 'aws_vpc.main_vpc.id') {
          primaryVpcRef = `aws_vpc.${resName}.id`;
        }
        mainBlocks.push(`resource "aws_vpc" "${resName}" {
  cidr_block           = var.vpc_cidr
  enable_dns_hostnames = true
  enable_dns_support   = true

  tags = {
    Name = "${node.label}"
  }
}\n`);
        outputBlocks.push(`output "${resName}_id" {
  value = aws_vpc.${resName}.id
}\n`);
        break;
      }

      case 'Subnet': {
        subnetIdx += 1;
        if (subnetIdx === 1) {
          primarySubnetRef = `aws_subnet.${resName}.id`;
        }
        mainBlocks.push(`resource "aws_subnet" "${resName}" {
  vpc_id                  = ${primaryVpcRef}
  cidr_block              = "10.0.${subnetIdx}.0/24"
  availability_zone       = data.aws_availability_zones.available.names[${(subnetIdx - 1) % 2}]
  map_public_ip_on_launch = true

  tags = {
    Name = "${node.label}"
  }
}\n`);
        break;
      }

      case 'SecurityGroup': {
        primarySgRef = `aws_security_group.${resName}.id`;
        mainBlocks.push(`resource "aws_security_group" "${resName}" {
  name        = "${resName}-sg"
  description = "${node.label}"
  vpc_id      = ${primaryVpcRef}

  ingress {
    from_port   = 80
    to_port     = 80
    protocol    = "tcp"
    cidr_blocks = ["0.0.0.0/0"]
  }

  ingress {
    from_port   = 443
    to_port     = 443
    protocol    = "tcp"
    cidr_blocks = ["0.0.0.0/0"]
  }

  egress {
    from_port   = 0
    to_port     = 0
    protocol    = "-1"
    cidr_blocks = ["0.0.0.0/0"]
  }
}\n`);
        break;
      }

      case 'IGW': {
        mainBlocks.push(`resource "aws_internet_gateway" "${resName}" {
  vpc_id = ${primaryVpcRef}

  tags = {
    Name = "${node.label}"
  }
}\n`);
        break;
      }

      case 'NAT': {
        mainBlocks.push(`resource "aws_eip" "${resName}_eip" {
  domain = "vpc"
}

resource "aws_nat_gateway" "${resName}" {
  allocation_id = aws_eip.${resName}_eip.id
  subnet_id     = ${primarySubnetRef}

  tags = {
    Name = "${node.label}"
  }
}\n`);
        break;
      }

      case 'WAF': {
        mainBlocks.push(`resource "aws_wafv2_web_acl" "${resName}" {
  name        = "${resName}-acl"
  description = "${node.label}"
  scope       = "REGIONAL"

  default_action {
    allow {}
  }

  rule {
    name     = "AWSManagedRulesCommonRuleSet"
    priority = 1

    override_action {
      none {}
    }

    statement {
      managed_rule_group_statement {
        name        = "AWSManagedRulesCommonRuleSet"
        vendor_name = "AWS"
      }
    }

    visibility_config {
      cloudwatch_metrics_enabled = true
      metric_name                = "${resName}-common-rules"
      sampled_requests_enabled   = true
    }
  }

  visibility_config {
    cloudwatch_metrics_enabled = true
    metric_name                = "${resName}-waf"
    sampled_requests_enabled   = true
  }
}\n`);
        break;
      }

      case 'CloudFront': {
        mainBlocks.push(`resource "aws_cloudfront_distribution" "${resName}" {
  enabled             = true
  comment             = "${node.label}"
  default_root_object = "index.html"

  origin {
    domain_name = "example-origin.s3.${safeRegion}.amazonaws.com"
    origin_id   = "${resName}-origin"
  }

  default_cache_behavior {
    allowed_methods        = ["GET", "HEAD", "OPTIONS"]
    cached_methods         = ["GET", "HEAD"]
    target_origin_id       = "${resName}-origin"
    viewer_protocol_policy = "redirect-to-https"

    forwarded_values {
      query_string = false
      cookies {
        forward = "none"
      }
    }
  }

  restrictions {
    geo_restriction {
      restriction_type = "none"
    }
  }

  viewer_certificate {
    cloudfront_default_certificate = true
  }
}\n`);
        outputBlocks.push(`output "${resName}_domain_name" {
  value = aws_cloudfront_distribution.${resName}.domain_name
}\n`);
        break;
      }

      case 'Route53': {
        mainBlocks.push(`resource "aws_route53_zone" "${resName}" {
  name = "example.com"
}\n`);
        break;
      }

      case 'ALB':
      case 'NLB': {
        const lbType = node.service === 'NLB' ? 'network' : 'application';
        mainBlocks.push(`resource "aws_lb" "${resName}" {
  name               = "${resName.slice(0, 28)}"
  internal           = false
  load_balancer_type = "${lbType}"
  subnets            = [${primarySubnetRef}]
  ${lbType === 'application' ? `security_groups    = [${primarySgRef}]` : ''}

  tags = {
    Name = "${node.label}"
  }
}\n`);
        outputBlocks.push(`output "${resName}_dns_name" {
  value = aws_lb.${resName}.dns_name
}\n`);
        break;
      }

      case 'APIGateway': {
        mainBlocks.push(`resource "aws_apigatewayv2_api" "${resName}" {
  name          = "${resName}-api"
  protocol_type = "HTTP"
}\n`);
        outputBlocks.push(`output "${resName}_api_endpoint" {
  value = aws_apigatewayv2_api.${resName}.api_endpoint
}\n`);
        break;
      }

      case 'EC2': {
        const instType = cfg.instanceType || 't3.medium';
        const volType = cfg.volumeType || 'gp3';
        const volSize = cfg.storageGb || 50;
        const isArm = instType.includes('g.');
        mainBlocks.push(`data "aws_ami" "${resName}_ami" {
  most_recent = true
  owners      = ["amazon"]

  filter {
    name   = "name"
    values = ["${isArm ? 'al2023-ami-2023*-arm64' : 'al2023-ami-2023*-x86_64'}"]
  }
}

resource "aws_instance" "${resName}" {
  ami                    = data.aws_ami.${resName}_ami.id
  instance_type          = "${instType}"
  subnet_id              = ${primarySubnetRef}
  vpc_security_group_ids = [${primarySgRef}]

  root_block_device {
    volume_type = "${volType}"
    volume_size = ${volSize}
    encrypted   = true
  }

  tags = {
    Name = "${node.label}"
  }
}\n`);
        outputBlocks.push(`output "${resName}_private_ip" {
  value = aws_instance.${resName}.private_ip
}\n`);
        break;
      }

      case 'ASG': {
        const instType = cfg.instanceType || 't3.medium';
        const desired = cfg.instanceCount || 4;
        mainBlocks.push(`resource "aws_launch_template" "${resName}_lt" {
  name_prefix   = "${resName}-"
  image_id      = "ami-0c55b159cbfafe1f0"
  instance_type = "${instType}"
}

resource "aws_autoscaling_group" "${resName}" {
  name                = "${resName}-asg"
  desired_capacity    = ${desired}
  max_size            = ${desired * 2}
  min_size            = 1
  vpc_zone_identifier = [${primarySubnetRef}]

  launch_template {
    id      = aws_launch_template.${resName}_lt.id
    version = "$Latest"
  }
}\n`);
        break;
      }

      case 'Lambda': {
        mainBlocks.push(`resource "aws_iam_role" "${resName}_role" {
  name = "${resName}-exec-role"

  assume_role_policy = jsonencode({
    Version = "2012-10-17"
    Statement = [{
      Action    = "sts:AssumeRole"
      Effect    = "Allow"
      Principal = { Service = "lambda.amazonaws.com" }
    }]
  })
}

resource "aws_lambda_function" "${resName}" {
  function_name = "${resName}"
  role          = aws_iam_role.${resName}_role.arn
  handler       = "index.handler"
  runtime       = "python3.12"
  filename      = "lambda_payload.zip"
}\n`);
        break;
      }

      case 'ECS': {
        mainBlocks.push(`resource "aws_ecs_cluster" "${resName}" {
  name = "${resName}-cluster"
}\n`);
        break;
      }

      case 'EKS': {
        mainBlocks.push(`resource "aws_iam_role" "${resName}_cluster_role" {
  name = "${resName}-eks-role"

  assume_role_policy = jsonencode({
    Version = "2012-10-17"
    Statement = [{
      Action    = "sts:AssumeRole"
      Effect    = "Allow"
      Principal = { Service = "eks.amazonaws.com" }
    }]
  })
}

resource "aws_eks_cluster" "${resName}" {
  name     = "${resName}-eks"
  role_arn = aws_iam_role.${resName}_cluster_role.arn

  vpc_config {
    subnet_ids = [${primarySubnetRef}]
  }
}\n`);
        break;
      }

      case 'RDS':
      case 'Aurora': {
        const dbClass = cfg.instanceType || 'db.t3.medium';
        const storage = cfg.storageGb || 100;
        const storageType = cfg.volumeType || 'gp3';
        mainBlocks.push(`resource "aws_db_instance" "${resName}" {
  identifier             = "${resName.replace(/_/g, '-')}"
  engine                 = "${node.service === 'Aurora' ? 'aurora-mysql' : 'mysql'}"
  instance_class         = "${dbClass}"
  allocated_storage      = ${storage}
  storage_type           = "${storageType}"
  db_name                = "appdb"
  username               = "admin"
  password               = "ChangeMeInSecretsManager123!"
  vpc_security_group_ids = [${primarySgRef}]
  skip_final_snapshot    = true
}\n`);
        outputBlocks.push(`output "${resName}_endpoint" {
  value = aws_db_instance.${resName}.endpoint
}\n`);
        break;
      }

      case 'DynamoDB': {
        mainBlocks.push(`resource "aws_dynamodb_table" "${resName}" {
  name         = "${resName}-table"
  billing_mode = "PAY_PER_REQUEST"
  hash_key     = "id"

  attribute {
    name = "id"
    type = "S"
  }
}\n`);
        break;
      }

      case 'ElastiCache': {
        mainBlocks.push(`resource "aws_elasticache_cluster" "${resName}" {
  cluster_id           = "${resName.replace(/_/g, '-').slice(0, 20)}"
  engine               = "redis"
  node_type            = "cache.t3.micro"
  num_cache_nodes      = 1
  parameter_group_name = "default.redis7"
}\n`);
        break;
      }

      case 'S3': {
        mainBlocks.push(`resource "aws_s3_bucket" "${resName}" {
  bucket_prefix = "${resName.replace(/_/g, '-')}-"
}

resource "aws_s3_bucket_public_access_block" "${resName}_pab" {
  bucket                  = aws_s3_bucket.${resName}.id
  block_public_acls       = true
  block_public_policy     = true
  ignore_public_acls      = true
  restrict_public_buckets = true
}\n`);
        outputBlocks.push(`output "${resName}_bucket_name" {
  value = aws_s3_bucket.${resName}.id
}\n`);
        break;
      }

      case 'EFS': {
        mainBlocks.push(`resource "aws_efs_file_system" "${resName}" {
  encrypted = true

  tags = {
    Name = "${node.label}"
  }
}\n`);
        break;
      }

      case 'SQS': {
        mainBlocks.push(`resource "aws_sqs_queue" "${resName}" {
  name = "${resName}-queue"
}\n`);
        break;
      }

      case 'SNS': {
        mainBlocks.push(`resource "aws_sns_topic" "${resName}" {
  name = "${resName}-topic"
}\n`);
        break;
      }

      case 'CloudWatch': {
        mainBlocks.push(`resource "aws_cloudwatch_log_group" "${resName}" {
  name              = "/aws/arch-studio/${resName}"
  retention_in_days = 14
}\n`);
        break;
      }

      case 'KMS': {
        mainBlocks.push(`resource "aws_kms_key" "${resName}" {
  description             = "${node.label}"
  deletion_window_in_days = 7
  enable_key_rotation     = true
}\n`);
        break;
      }

      case 'SecretsManager': {
        mainBlocks.push(`resource "aws_secretsmanager_secret" "${resName}" {
  name = "${resName}-secret"
}\n`);
        break;
      }

      default: {
        mainBlocks.push(`# ${node.service} (${node.label}) — configure custom module block\n`);
      }
    }
  }

  return {
    'provider.tf': providerTf,
    'variables.tf': variablesTf,
    'main.tf': mainBlocks.join('\n'),
    'outputs.tf': outputBlocks.join('\n')
  };
}